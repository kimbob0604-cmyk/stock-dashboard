"""
disclosure_category.py — DART 공시 제목(report_nm) → 카테고리.

제목만 본다(원문을 열지 않는다). 규칙은 **위에서부터 처음 맞는 것** 하나다 — 순서가
의미를 갖는다. 예: '자기주식처분결정' 은 '처분결정'(자산양수도)보다 '자기주식'(주주환원)
이 먼저 잡혀야 하고, '합병계약' 은 '계약'(계약)보다 '합병'(회사구조)이 먼저다.

제목 앞의 정정 표시('[기재정정]', '[첨부정정]' 등)와 괄호 속 '(자율공시)' 같은 꼬리표는
떼고 본다. 어느 규칙에도 안 맞으면 '기타'.
"""
from __future__ import annotations

import re

# (카테고리, 정규식) — 순서대로 본다.
RULES: tuple[tuple[str, str], ...] = (
    ("해명", r"조회공시|풍문|보도.{0,6}해명|해명"),
    ("사건사고", r"소송|횡령|배임|영업정지|부도|회생절차|파산|화재|사고|관리종목|상장폐지|"
                 r"불성실공시|감사의견|거래정지|매매거래정지|상장적격성|투자주의환기|"
                 r"실질심사|개선계획|벌금|과징금|제재"),
    ("실적", r"잠정\)?실적|영업실적|손익구조|매출액또는손익|결산실적|분기보고서|반기보고서|"
             r"사업보고서|감사보고서|실적"),
    ("주주환원", r"배당|자기주식|자사주|주식소각|이익소각|소각결정|주주환원"),
    # 특수관계인·계열사 거래와 남을 위한 보증·담보·대여 — '자금차입'·'주식의처분' 이 아래
    # 자금조달·자산양수도에 먼저 잡히지 않게 그 위에 둔다(2026-11-01, 기타 109건 정리)
    # 담보제공은 '…결정'(남을 위한 담보)만 — '최대주주변경을수반하는주식담보제공계약' 은 회사구조
    ("내부거래·보증", r"특수관계인|계열회사|채무보증|담보제공결정|금전대여|"
                      r"약관에의한금융거래"),
    ("자금조달", r"유상증자|전환사채|신주인수권부사채|교환사채|사채권발행|증권발행|"
                 r"증권신고서|자금조달|단기차입|차입금|전환청구권|교환청구권|"
                 r"신주인수권행사|전환가액|교환가액|행사가액|투자설명서|일괄신고|소액공모"),
    ("회사구조", r"합병|분할|주식교환|주식이전|감자|무상증자|액면분할|주식병합|상호변경|"
                 r"최대주주변경|지주회사|영업양수|영업양도|해산"),
    ("신규시설투자", r"신규시설투자|시설투자"),
    ("자산양수도", r"양수|양도|취득결정|처분결정|출자증권|유형자산"),
    ("계약", r"공급계약|판매.{0,4}계약|계약체결|수주|계약"),
    ("지분공시", r"대량보유|소유상황|소유주식|임원.{0,2}주요주주|최대주주등|특정증권등"),
    ("주주총회", r"주주총회|주주명부폐쇄|기준일설정|의결권대리행사"),
    ("경영계획", r"기업가치제고|밸류업|경영계획|장래사업|경영목표|전망|기업설명회|\bIR\b"),
    ("주요경영사항", r"주요경영사항|기술도입|기술이전|특허|임상|품목허가|허가|승인|자율공시|"
                     r"대표이사|임원.{0,4}(선임|사임|퇴임)|본점소재지|소속부변경"),
)
CATEGORIES: tuple[str, ...] = tuple(c for c, _ in RULES) + ("기타",)
_COMPILED = tuple((c, re.compile(p)) for c, p in RULES)
_PREFIX = re.compile(r"^\s*(\[[^\]]*\]\s*)+")


def clean_title(title: str) -> str:
    """'[기재정정]주요사항보고서(유상증자결정)' → '주요사항보고서(유상증자결정)'."""
    return _PREFIX.sub("", title or "").strip()


def categorize(title: str) -> str:
    t = clean_title(title).replace(" ", "")
    for cat, rx in _COMPILED:
        if rx.search(t):
            return cat
    return "기타"


def counts(titles) -> dict[str, int]:
    """카테고리별 건수 — 0 인 카테고리도 키로 둔다(칩 순서가 흔들리지 않게)."""
    out = {c: 0 for c in CATEGORIES}
    for t in titles:
        out[categorize(t)] += 1
    return out
